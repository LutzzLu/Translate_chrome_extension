  // Optional section number in front ("2.", "3.1", "IV."), optional ":" or "." after.
  const HEADING_RE = /^\s*((?:\d+(?:\.\d+)*\.?|[IVX]+\.)\s+)?(.+?)\s*([.:：])?\s*$/;

  globalThis.ptxGlossary = function ptxGlossary(text, targetLang) {
    const table = TABLES[targetLang];
    if (!table || !text || text.length > 60) return null;
    const m = String(text).replace(/\s+/g, ' ').match(HEADING_RE);
    if (!m) return null;
    const key = m[2].toLowerCase().replace(/[’`]/g, "'");
    const hit = table[key];
    if (!hit) return null;
    return `${m[1] || ''}${hit}${m[3] && m[3] !== '.' ? '：' : ''}`;
  };
